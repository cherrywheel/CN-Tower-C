export type Language = 'en' | 'ru' | 'be';
export type PageId = 'home' | 'download' | 'targets' | 'canary' | 'build' | 'play' | 'python' | 'legal';

export function getInitialLanguage(): Language {
  try {
    const saved = localStorage.getItem('cn_tower_lang');
    if (saved === 'ru' || saved === 'en' || saved === 'be') return saved;
  } catch {
    // ignore
  }

  if (typeof window !== 'undefined') {
    const navLang = window.navigator.language.toLowerCase();
    if (navLang.startsWith('be')) return 'be';
    if (navLang.startsWith('ru')) return 'ru';
  }
  return 'en';
}

export function saveLanguage(lang: Language) {
  try {
    localStorage.setItem('cn_tower_lang', lang);
  } catch {
    // ignore
  }
}

